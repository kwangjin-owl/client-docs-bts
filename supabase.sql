-- ------------------------------------------------------------
-- 1. 접수 (applications)
-- ------------------------------------------------------------
create table if not exists applications (
  id bigint generated always as identity primary key,
  created_at timestamptz default now(),

  track text not null,              -- 국가기술 / 전문 / 보건
  agency text not null,             -- 두두넷 / 두두보건
  cert_code text,                   -- 7910, P002, H001 ...
  cert_name text not null,

  name text not null,
  phone text not null,              -- 010-0000-0000 으로 통일
  gender text,                      -- M / F 로 통일
  birth_date date,                  -- YYYY-MM-DD 로 통일
  email text,

  exam_region text,
  exam_date date,
  exam_session text,

  fee_amount int,
  fee_discount_type text,
  fee_final int,
  payment_method text,              -- 신용카드 / 계좌이체 / 가상계좌 로 통일
  status text default '접수완료',    -- 접수완료 / 결제대기 / 취소 / 문의

  usage_context text,               -- 본인단독 / 가족보조 / 복지관 / 대리접수
  channel text,                     -- 온라인 / 전화 / 방문  (접수대장의 접수경로)
  memo text,                        -- 접수대장의 비고

  receipt_no text unique,           -- 접수번호 (손님에게 알려 드리는 번호)
  pay_status text default '대기',   -- 결제 상태 (두두넷에서 정해지는 값)
  fee_discount_amount int,          -- 감면 금액
  agreed_privacy boolean default false,  -- 개인정보 수집 동의
  agreed_terms boolean default false,    -- 이용약관 동의
  disability_type text,             -- 편의제공 신청 (두두보건)
  accommodation_request text,

  extra jsonb                       -- 트랙별로만 있는 칸
);

alter table applications enable row level security;
drop policy if exists "anon insert" on applications;
create policy "anon insert" on applications for insert to anon with check (true);
drop policy if exists "anon read" on applications;
create policy "anon read"   on applications for select to anon using (true);
drop policy if exists "anon update" on applications;
create policy "anon update" on applications for update to anon using (true) with check (true);
-- 직원이 잘못 넣은 접수를 지울 수 있어야 한다
drop policy if exists "anon delete" on applications;
create policy "anon delete" on applications for delete to anon using (true);


-- ------------------------------------------------------------
-- 2. 챗봇 문서 (docs)
--    FAQ 어드민에서 고치면 챗봇 답이 바로 바뀝니다.
-- ------------------------------------------------------------
create table if not exists docs (
  id bigint generated always as identity primary key,
  updated_at timestamptz default now(),
  cert text,
  title text not null,
  body text not null,
  source text
);

alter table docs enable row level security;
drop policy if exists "anon read docs" on docs;
create policy "anon read docs"   on docs for select to anon using (true);
drop policy if exists "anon update docs" on docs;
create policy "anon update docs" on docs for update to anon using (true) with check (true);
drop policy if exists "anon insert docs" on docs;
create policy "anon insert docs" on docs for insert to anon with check (true);
drop policy if exists "anon delete docs" on docs;
create policy "anon delete docs" on docs for delete to anon using (true);

-- 같은 제목이 두 번 들어가지 않게 막는다.
-- 이미 있는 문서는 건드리지 않으므로, 화면에서 고치신 내용이 지워지지 않아요.
-- 상담기록은 제목이 겹치므로 (제목+본문)으로 중복을 본다
drop index if exists docs_title_key;
create unique index if not exists docs_key on docs (title, md5(body));

