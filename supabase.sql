-- 결제와 처리를 갈라 놓는다
-- 세 기관 CSV 는 원래 결제상태와 접수상태가 따로 있었는데
-- 통합할 때 하나로 합쳐서 '접수완료 다음이 결제대기' 처럼 순서가 엉켰습니다.
